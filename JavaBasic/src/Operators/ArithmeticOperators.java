package Operators;

public class ArithmeticOperators {
    public static void main(){
        /*
         Arithmetic Operators are used for mathematical Operation
         Operator   Meaning	            Example
            +	    Addition	        a + b
            -	    Subtraction	        a - b
            *	    Multiplication	    a * b
            /	    Division	        a / b
            %	    Modulus (remainder)	a % b
         */


        int a=10;
        int b=2;
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
        System.out.println(a%b);

        String str1="Hello";
        String str2="World";
        System.out.println(str1+str2);
    }
}
